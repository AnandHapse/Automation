// Ternary Operator is a shorthand for if-else statement
// condition ? expression1 : expression2
// if condition is true, then expression1 is executed, otherwise expression2 is executed
// it is a single line statement
// it is also known as conditional operator
// Ternary (Conditional) Operator (?:)
// condition, either this or that.


let Age = 20;
let is_anand_go_to_Goa = Age > 18 ? "yes" : "no";
console.log(is_anand_go_to_Goa);


// condiition ? value (If True) : value (If False)